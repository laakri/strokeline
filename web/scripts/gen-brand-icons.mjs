import fs from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const here = path.dirname(fileURLToPath(import.meta.url))
const webRoot = path.resolve(here, "..")
const manifestPath = path.join(here, "brand-icons.json")
const outputDir = path.join(webRoot, "public", "brand-icons")
const catalogFile = path.join(
  webRoot,
  "src",
  "defaults",
  "brandIcons.generated.ts"
)
const brands = JSON.parse(await fs.readFile(manifestPath, "utf8"))

if (
  !Array.isArray(brands) ||
  brands.some((brand) => !brand.slug || !brand.title || !brand.category)
) {
  throw new Error("Every brand icon needs a slug, title, and category.")
}
if (new Set(brands.map((brand) => brand.slug)).size !== brands.length) {
  throw new Error("Brand icon slugs must be unique.")
}

await fs.mkdir(outputDir, { recursive: true })
const failures = []
let next = 0
async function worker() {
  while (next < brands.length) {
    const brand = brands[next++]
    const url = `https://cdn.simpleicons.org/${encodeURIComponent(brand.slug)}`
    try {
      const response = await fetch(url)
      if (!response.ok) throw new Error(`HTTP ${response.status}`)
      const svg = await response.text()
      if (!/^\s*<svg\b/i.test(svg) || !svg.includes("</svg>"))
        throw new Error("Response was not an SVG")
      await fs.writeFile(path.join(outputDir, `${brand.slug}.svg`), svg + "\n")
    } catch (error) {
      failures.push(
        `${brand.slug}: ${error instanceof Error ? error.message : String(error)}`
      )
    }
  }
}
await Promise.all(Array.from({ length: 5 }, () => worker()))

const missing = new Set(failures.map((failure) => failure.split(":")[0]))
const availableBrands = brands.filter((brand) => !missing.has(brand.slug))
const catalog = availableBrands.map(
  ({ slug, title, category, keywords = "" }) => ({
    slug,
    title,
    category,
    keywords,
  })
)
const generated =
  `// Generated by scripts/gen-brand-icons.mjs from scripts/brand-icons.json. Do not edit by hand.\n` +
  `export interface BrandIcon { slug: string; title: string; category: string; keywords: string }\n` +
  `export const BRAND_ICON_CATALOG: BrandIcon[] = ${JSON.stringify(catalog, null, 2)}\n`
await fs.writeFile(catalogFile, generated)

console.log(`Generated ${availableBrands.length}/${brands.length} brand SVGs.`)
if (failures.length) {
  console.error("Unavailable icons (excluded from the generated catalog):")
  console.error(failures.join("\n"))
  process.exitCode = 1
}
